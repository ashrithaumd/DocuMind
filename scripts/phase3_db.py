"""The Phase 3 database (docker-compose.phase3.yml): set up, start, migrate,
and run commands against it, without ever printing a password.

    backend/.venv/Scripts/python scripts/phase3_db.py init     # passwords into .env, once
    backend/.venv/Scripts/python scripts/phase3_db.py up       # start, wait, run the migrate step
    backend/.venv/Scripts/python scripts/phase3_db.py run -- python scripts/load_corpus.py
    backend/.venv/Scripts/python scripts/phase3_db.py down     # stop; the data volume stays

`run` puts the owner URL in MIGRATION_DATABASE_URL and the documind_app URL
in DATABASE_URL for the command it starts, so scripts like load_corpus.py,
setup_eval_admin.py and seed_test_users.py find them there; nothing goes on
a command line or into a log. Passwords live only in the repo-root .env
(PHASE3_POSTGRES_PASSWORD, PHASE3_APP_DB_PASSWORD), generated by `init`.
The port defaults to 5450 (PHASE3_DB_PORT).
"""
import os
import re
import secrets
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ENV_FILE = REPO / ".env"
COMPOSE = ["docker", "compose", "-f", str(REPO / "docker-compose.phase3.yml")]
SECRETS = ("PHASE3_POSTGRES_PASSWORD", "PHASE3_APP_DB_PASSWORD")


def read_env(path: Path = ENV_FILE) -> dict[str, str]:
    from dotenv import dotenv_values

    return {k: v for k, v in dotenv_values(path).items() if v is not None} if path.exists() else {}


def ensure_secrets(path: Path = ENV_FILE) -> list[str]:
    """Append any missing Phase 3 password to .env; never change an existing
    one. Returns the names added (never their values)."""
    current = read_env(path)
    missing = [name for name in SECRETS if not current.get(name)]
    if missing:
        # Raw read: read_text() would turn CRLF into LF and hide the file's line endings.
        text = path.read_bytes().decode("utf-8") if path.exists() else ""
        nl = "\r\n" if "\r\n" in text else "\n"
        lines = [] if not text or text.endswith(("\n", "\r\n")) else [""]
        if not any(line.startswith("# Phase 3 database") for line in text.splitlines()):
            lines.append("# Phase 3 database (scripts/phase3_db.py)")
        lines += [f"{name}={secrets.token_urlsafe(32)}" for name in missing]
        with path.open("a", encoding="utf-8", newline="") as fh:
            fh.write(nl.join(lines) + nl)
    return missing


def urls(env: dict[str, str]) -> dict[str, str]:
    """The owner and app URLs, with passwords quoted for a URL."""
    from sqlalchemy.engine import URL

    port = int(env.get("PHASE3_DB_PORT") or 5450)

    def url(user: str, password: str) -> str:
        return URL.create("postgresql+psycopg2", username=user, password=password,
                          host="localhost", port=port,
                          database="documind").render_as_string(hide_password=False)

    return {"MIGRATION_DATABASE_URL": url("documind", env["PHASE3_POSTGRES_PASSWORD"]),
            "DATABASE_URL": url("documind_app", env["PHASE3_APP_DB_PASSWORD"])}


def command_env(env: dict[str, str]) -> dict[str, str]:
    """The environment for `run`: the caller's, plus the two URLs."""
    return {**os.environ, **urls(env)}


def main(argv: list[str]) -> int:
    if not argv or argv[0] not in {"init", "up", "run", "down"}:
        print(__doc__)
        return 2
    action = argv[0]
    if action == "init":
        added = ensure_secrets()
        print(f"Added {', '.join(added)} to .env (values not shown)." if added
              else "Phase 3 passwords already in .env; left as they are.")
        return 0
    if action == "down":
        return subprocess.run(COMPOSE + ["stop"], cwd=REPO).returncode
    env = read_env()
    if not all(env.get(n) for n in SECRETS):
        print("Run `scripts/phase3_db.py init` first.", file=sys.stderr)
        return 2
    if action == "up":
        started = subprocess.run(COMPOSE + ["up", "-d", "--wait"], cwd=REPO)
        if started.returncode:
            return started.returncode
        # The migrate step, as the owner; it also sets documind_app's password.
        migrated = subprocess.run([sys.executable, "migrate.py"], cwd=REPO / "backend",
                                  env=command_env(env))
        return migrated.returncode
    # run -- command...
    args = argv[1:]
    if args[:1] == ["--"]:
        args = args[1:]
    if not args:
        print("Nothing to run: phase3_db.py run -- <command>", file=sys.stderr)
        return 2
    if args[0] == "python":  # the venv this script runs in, not whatever is on PATH
        args = [sys.executable] + args[1:]
    return subprocess.run(args, cwd=REPO, env=command_env(env)).returncode


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
